/** Upper-cases with Turkish rules when needed (i → İ, ı → I); `toUpperCase` alone turns "senin" into "SENIN". */
export function upper(text: string, lang: Lang): string {
  return (lang === 'tr' ? text.replace(/i/g, 'İ').replace(/ı/g, 'I') : text).toUpperCase();
}

